class PrintDemo{
	public static void main(String args[]){
		System.out.println("My name is Janahan");//Using Println
		System.out.println("My Father name Thavarajan");
		System.out.println("My Age is 26");
		
		System.out.println();
		
		System.out.print("My name is Janahan");//Using Print
		System.out.print("My Father name Thavarajan");
		System.out.print("My Age is 26");
		
		System.out.println();
		
		//Using print with \n
		System.out.print("My name is Janahan\n");
		System.out.print("My Father name Thavarajan\n");
		System.out.print("My Age is 26\n");
	}
}